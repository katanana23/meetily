// Три слоя против пустых записей: пороги и сроки в одном месте.
//
// 1. Правила (content-rules.ts, мгновенно при «Остановить»): считаются уникальные значимые
//    слова. До EMPTY_MAX_WORDS включительно запись не сохраняется («Пустая запись - не
//    сохранена»), до CHECK_MAX_WORDS включительно сохраняется и уходит на проверку моделью,
//    больше сохраняется без проверки.
// 2. Проверка моделью (content-check.ts): тот же локальный провайдер, что для итогов, ответ
//    да/нет. «Нет» переносит встречу в корзину; модель недоступна или молчит дольше
//    MODEL_CHECK_TIMEOUT_MS: встреча остаётся в списке.
// 3. Корзина (meeting-trash.ts): через TRASH_TTL_DAYS дней встреча удаляется насовсем вместе
//    с папкой записи.
//
// Правила применяются только к новой записи при «Остановить»: встречи, уже лежащие в базе,
// и импорт аудио они не трогают.

/** Столько значимых слов и меньше: пустая запись, не сохраняется. */
export const EMPTY_MAX_WORDS = 2;
/** Столько значимых слов и меньше (но больше EMPTY_MAX_WORDS): сохраняется и проверяется моделью. */
export const CHECK_MAX_WORDS = 15;
/** Столько чисел подряд и больше: счёт («раз, два, три»), а не данные. */
export const COUNTING_RUN = 3;
/** Сколько ждать ответа модели; дольше — встреча остаётся в списке. */
export const MODEL_CHECK_TIMEOUT_MS = 20_000;
/** Сколько дней встреча лежит в корзине, потом удаляется насовсем (база и папка записи). */
export const TRASH_TTL_DAYS = 30;
