/** Перевод строки оригинала или null, если перевода нет. */
export function translate(text: string): string | null {
  const key = text.replace(/\s+/g, ' ').trim();
  if (!key) return null;
  if (key in EXACT) return EXACT[key];
  for (const [re, fn] of PATTERNS) {
    const m = key.match(re);
    if (m) return fn(...m);
  }
  // Бренд оригинала во фразе без перевода: хотя бы не показываем чужое имя.
  // Пути к файлам не трогаем: папка на диске называется так, как её создало ядро.
  if (key.includes('Meetily') && !/[\\/]/.test(key)) return key.replace(/Meetily/g, 'ShadeNotes');
  return null;
}

/** Есть ли в строке латиница, похожая на непереведённый текст интерфейса. */
export function looksUntranslated(text: string): boolean {
  return /[A-Za-z]{3,}\s+[A-Za-z]{3,}/.test(text) && !/[А-Яа-яЁё]/.test(text);
}
